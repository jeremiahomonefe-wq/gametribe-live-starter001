// Adds your own pictures to the "Guess the Picture" mix.
//   1. Put the images in my-pictures/ and list them in my-pictures/pictures.csv
//   2. npm run add-pictures
//   3. npm run build (and redeploy)
// The CSV is the source of truth: every run rebuilds client/public/pictures/custom/ and server/src/custom-pictures.js
// from it. Flags and logos are never touched.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { parsePictureRows, prepareCustom } from '../server/src/picture-import.js';
import { PICTURE_POOL } from '../server/src/picture-pool.js';

const root = process.env.ROOT_DIR ? path.resolve(process.env.ROOT_DIR) : path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(root, 'my-pictures');
const csvFile = path.join(src, 'pictures.csv');
const fail = (lines) => { console.error(lines.join('\n')); process.exit(1); };

if (!fs.existsSync(csvFile)) fail([`Could not find ${path.relative(root, csvFile)}.`, 'Create it with the header: file,category,answer,wrong_1,wrong_2,wrong_3,question']);
const parsed = parsePictureRows(fs.readFileSync(csvFile, 'utf8'));
if (parsed.fatal) fail([parsed.fatal]);

const files = Object.fromEntries(fs.readdirSync(src).filter((f) => fs.statSync(path.join(src, f)).isFile()).map((f) => [f, fs.statSync(path.join(src, f)).size]));
// Hashed names: the address of a picture must never give the answer away.
const makeName = (category, answer, ext) => `${crypto.createHash('sha1').update(`gt-custom:${category}:${answer}`).digest('hex').slice(0, 10)}.${ext}`;
const { items, copies, problems } = prepareCustom(parsed.rows, { builtIn: PICTURE_POOL, files, makeName });
if (problems.length) fail(['Nothing was changed. Fix these and run it again:', ...problems.map((p) => `  ${p.row ? `Row ${p.row}: ` : ''}${p.message}`)]);

const outDir = path.join(root, 'client/public/pictures/custom');
fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(outDir, { recursive: true });
for (const c of copies) fs.copyFileSync(path.join(src, c.from), path.join(outDir, c.to));
fs.mkdirSync(path.join(root, 'server/src'), { recursive: true });
fs.writeFileSync(path.join(root, 'server/src/custom-pictures.js'), `// GENERATED by scripts/add-pictures.mjs from my-pictures/pictures.csv. Do not edit by hand.
export const CUSTOM_PICTURES = ${JSON.stringify(items, null, 2)};
`);
const cats = [...new Set(items.map((i) => i.category))];
console.log(`Added ${items.length} picture${items.length === 1 ? '' : 's'}${cats.length ? ` in ${cats.join(', ')}` : ''}. Now run: npm run build`);
