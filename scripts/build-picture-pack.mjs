// Builds the picture pool for the "Guess the Picture" game: copies flag and logo SVGs into client/public/pictures
// and writes server/src/picture-pool.js (GENERATED). Run once, then commit the results.
//
//   npm i --no-save flag-icons simple-icons      (any temp folder works too)
//   PACKS_DIR=node_modules node scripts/build-picture-pack.mjs
//
// File names are a hash of the answer, so the address of a picture never gives the answer away.
// Flags: flag-icons (MIT). Logos: Simple Icons (CC0 data). The brands themselves own their trademarks.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packs = path.resolve(process.env.PACKS_DIR || 'node_modules');
const out = path.join(root, 'client/public/pictures');
const hash = (category, answer) => crypto.createHash('sha1').update(`gt-pictures:${category}:${answer}`).digest('hex').slice(0, 10);

const FLAGS = { ng: 'Nigeria', gh: 'Ghana', za: 'South Africa', ke: 'Kenya', ma: 'Morocco', sn: 'Senegal', et: 'Ethiopia', tz: 'Tanzania', ug: 'Uganda', cm: 'Cameroon', ci: "Côte d'Ivoire", dz: 'Algeria', eg: 'Egypt', br: 'Brazil', ar: 'Argentina', us: 'United States', gb: 'United Kingdom', fr: 'France', de: 'Germany', it: 'Italy', pt: 'Portugal', nl: 'Netherlands', jp: 'Japan', cn: 'China', kr: 'South Korea', in: 'India', au: 'Australia', ca: 'Canada', tr: 'Turkey', ae: 'United Arab Emirates', ru: 'Russia', se: 'Sweden', no: 'Norway', ch: 'Switzerland', gr: 'Greece', ie: 'Ireland', jm: 'Jamaica', co: 'Colombia', cl: 'Chile', pk: 'Pakistan', id: 'Indonesia', th: 'Thailand', ua: 'Ukraine', pl: 'Poland', be: 'Belgium', dk: 'Denmark', fi: 'Finland', nz: 'New Zealand' };
const BRANDS = ['Nike', 'Adidas', 'Apple', 'Google', 'Netflix', 'Spotify', 'Starbucks', "McDonald's", 'Coca-Cola', 'YouTube', 'Instagram', 'Facebook', 'WhatsApp', 'TikTok', 'Telegram', 'Samsung', 'Tesla', 'BMW', 'Toyota', 'Ford', 'Ferrari', 'Lamborghini', 'Puma', 'IKEA', 'PlayStation', 'Uber', 'Airbnb', 'PayPal', 'Visa', 'Audi', 'Volkswagen', 'Honda', 'Pinterest', 'Reddit', 'Discord', 'Twitch', 'Huawei', 'Intel', 'Burger King', 'KFC', 'Red Bull', 'Stripe', 'Android', 'Bitcoin', 'Binance', 'Shopify', 'Zoom', 'Emirates'];

// Only flags and logos are rebuilt. Pictures you add with `npm run add-pictures` live in pictures/custom and are never touched.
for (const dir of ['flags', 'logos']) { fs.rmSync(path.join(out, dir), { recursive: true, force: true }); fs.mkdirSync(path.join(out, dir), { recursive: true }); }
const pool = [];

for (const [code, name] of Object.entries(FLAGS)) {
  const file = path.join(packs, 'flag-icons/flags/4x3', `${code}.svg`);
  // Drop the id on the root <svg> and the country code inside internal ids (they would name the answer),
  // but keep the internal ids themselves: <use href="#x"> still needs them.
  const svg = fs.readFileSync(file, 'utf8')
    .replace(/(<svg[^>]*?)\s+id="[^"]*"/, '$1')
    .replace(new RegExp(`(["#(])${code}-(?=[A-Za-z0-9])`, 'g'), '$1p-')
    .replace(/<title>.*?<\/title>/g, '').trim();
  const name_ = `${hash('flags', name)}.svg`;
  fs.writeFileSync(path.join(out, 'flags', name_), svg);
  pool.push({ category: 'Flags', answer: name, image: `/pictures/flags/${name_}` });
}

const data = JSON.parse(fs.readFileSync(path.join(packs, 'simple-icons/data/simple-icons.json'), 'utf8'));
const luminance = (hex) => { const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4)); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
for (const brand of BRANDS) {
  const item = data.find((i) => i.title === brand);
  if (!item) { console.warn(`skipped ${brand}: not in Simple Icons`); continue; }
  const raw = fs.readFileSync(path.join(packs, 'simple-icons/icons', `${item.slug}.svg`), 'utf8');
  const d = raw.match(/<path d="([^"]+)"/)?.[1];
  if (!d) { console.warn(`skipped ${brand}: no path`); continue; }
  const light = luminance(item.hex) > 0.45; // pale logos sit on a dark tile so they stay readable
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><rect width="24" height="24" rx="3" fill="${light ? '#1b1b2f' : '#ffffff'}"/><path transform="translate(3.6 3.6) scale(0.7)" fill="#${item.hex}" d="${d}"/></svg>`;
  const name_ = `${hash('logos', brand)}.svg`;
  fs.writeFileSync(path.join(out, 'logos', name_), svg);
  pool.push({ category: 'Logos', answer: brand, image: `/pictures/logos/${name_}` });
}

fs.writeFileSync(path.join(root, 'server/src/picture-pool.js'), `// GENERATED by scripts/build-picture-pack.mjs. Do not edit by hand.
// Flags: flag-icons (MIT). Logos: Simple Icons (CC0 data); every logo remains the trademark of its owner.
export const PICTURE_POOL = ${JSON.stringify(pool, null, 2)};
`);
console.log(`Wrote ${pool.length} pictures (${pool.filter((p) => p.category === 'Flags').length} flags, ${pool.filter((p) => p.category === 'Logos').length} logos).`);
